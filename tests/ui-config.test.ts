import { test, expect, beforeEach } from 'vitest';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync, appendFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { readUiConfig, uiConfigPath, uiEnabled, globToRegExp, staleTargets } from '../src/ui/config.js';
import { tokensDir } from '../src/ui/tokens.js';
import { cmdGenTokens } from '../src/cli.js';

let root: string;
const TOKENS = { color: { $type: 'color', brand: { primary: { $value: '#1E5BFF' } } } };
const writeTokens = (doc: unknown) => {
  mkdirSync(tokensDir(root), { recursive: true });
  writeFileSync(join(tokensDir(root), 'base.json'), JSON.stringify(doc));
};
const writeCfg = (cfg: unknown) => writeFileSync(uiConfigPath(root), JSON.stringify(cfg));
beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), 'ad-uicfg-'));
  writeTokens(TOKENS);
});

test('readUiConfig defaults when ui.json is missing', () => {
  expect(readUiConfig(root)).toEqual({ targets: [], ignore: [], hardcoded: 'warn', modes: [] });
});

test('readUiConfig rejects unknown lang', () => {
  writeCfg({ targets: [{ lang: 'cobol', out: 'x.cob' }] });
  expect(() => readUiConfig(root)).toThrow(/cobol/);
});

test('uiEnabled follows the tokens/components folders', () => {
  expect(uiEnabled(root)).toBe(true);
  expect(uiEnabled(mkdtempSync(join(tmpdir(), 'ad-uicfg-')))).toBe(false);
});

test('globToRegExp', () => {
  const deep = globToRegExp('legacy/**/colors.dart');
  expect(deep.test('legacy/a/b/colors.dart')).toBe(true);
  expect(deep.test('legacy/colors.dart')).toBe(true);
  expect(globToRegExp('*.css').test('a.css')).toBe(true);
  expect(globToRegExp('*.css').test('x/a.css')).toBe(false);
  expect(globToRegExp('**/*.css').test('x/a.css')).toBe(true);
  expect(globToRegExp('a?.css').test('ab.css')).toBe(true);
});

test('cmdGenTokens writes every target and creates folders', () => {
  writeCfg({ targets: [{ lang: 'css', out: 'web/ds/tokens.css' }, { lang: 'dart', out: 'mobile/lib/ds/tokens.dart', className: 'AppTokens' }] });
  const msg = cmdGenTokens(root);
  expect(msg).toContain('web/ds/tokens.css');
  expect(readFileSync(join(root, 'web/ds/tokens.css'), 'utf8').startsWith('/* Generated by antidrift')).toBe(true);
  expect(readFileSync(join(root, 'mobile/lib/ds/tokens.dart'), 'utf8')).toContain('abstract final class AppTokens');
});

test('cmdGenTokens with no targets explains how to add one', () => {
  expect(cmdGenTokens(root)).toMatch(/ui\.json/);
});

test('cmdGenTokens with lang+out writes just that file', () => {
  const out = join(root, 'one.css');
  cmdGenTokens(root, 'css', out);
  expect(existsSync(out)).toBe(true);
  expect(existsSync(join(root, 'web'))).toBe(false);
});

test('staleTargets treats a missing file as stale', () => {
  writeCfg({ targets: [{ lang: 'css', out: 'web/tokens.css' }, { lang: 'dart', out: 'app/tokens.dart' }] });
  expect(staleTargets(root).map((t) => t.out)).toEqual(['web/tokens.css', 'app/tokens.dart']);
  cmdGenTokens(root);
  expect(staleTargets(root)).toEqual([]);
  appendFileSync(join(root, 'web/tokens.css'), '/* x */');
  expect(staleTargets(root).map((t) => t.out)).toEqual(['web/tokens.css']);
  cmdGenTokens(root);
  writeTokens({ color: { $type: 'color', brand: { primary: { $value: '#000000' } } } });
  expect(staleTargets(root)).toHaveLength(2);
});
