import type { Token, TokenValue } from './tokens.js';

export interface TokenEmitterOptions {
  className?: string;
}
export interface TokenEmitter {
  lang: string;
  ext: string;
  emit(tokens: Map<string, Token>, opts?: TokenEmitterOptions): string;
}

export const GENERATED_HEADER = 'Generated by antidrift from .antidrift/tokens — do not edit.';

const sorted = (tokens: Map<string, Token>) => [...tokens.values()].sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));

/** Map every token path to an identifier, failing loudly when two paths collapse to the same one. */
function nameAll(tokens: Map<string, Token>, name: (path: string) => string): Map<string, string> {
  const byName = new Map<string, string>();
  const out = new Map<string, string>();
  for (const t of sorted(tokens)) {
    const n = name(t.path);
    const other = byName.get(n);
    if (other) throw new Error(`tokens ${other} and ${t.path} both map to the identifier ${n}; rename one`);
    byName.set(n, t.path);
    out.set(t.path, n);
  }
  return out;
}

// Values below come from validated tokens (see tokens.ts), so they can't carry code.
const cssHex = (hex: string) => (hex.endsWith('FF') ? hex.slice(0, 7) : hex).toLowerCase();

function cssValue(v: TokenValue): string {
  switch (v.type) {
    case 'color':
      return cssHex(v.hex);
    case 'dimension':
      return `${v.value}${v.unit}`;
    case 'fontFamily':
      return v.families.map((f) => `"${f}"`).join(', ');
    case 'fontWeight':
      return String(v.weight);
    case 'number':
      return String(v.value);
    case 'duration':
      return `${v.ms}ms`;
  }
}

export const cssTokenEmitter: TokenEmitter = {
  lang: 'css',
  ext: 'css',
  emit(tokens) {
    const names = nameAll(tokens, (p) => `--${p.replace(/\./g, '-')}`);
    const lines = sorted(tokens).map((t) => {
      const value = t.aliasOf ? `var(${names.get(t.aliasOf)})` : cssValue(t.value);
      return `  ${names.get(t.path)}: ${value};`;
    });
    return `/* ${GENERATED_HEADER} */\n:root {\n${lines.join('\n')}\n}\n`;
  },
};

const DART_RESERVED = new Set(
  ('abstract as assert async await base break case catch class const continue covariant default deferred do dynamic else ' +
    'enum export extends extension external factory false final finally for Function get hide if implements import in ' +
    'interface is late library mixin new null of on operator part required rethrow return sealed set show static super ' +
    'switch sync this throw true try type typedef var void when while with yield').split(' '),
);

function dartName(path: string): string {
  const words = path.split(/[._-]+/).filter(Boolean);
  let n = words.map((w, i) => (i === 0 ? w[0].toLowerCase() + w.slice(1) : w[0].toUpperCase() + w.slice(1))).join('');
  if (/^\d/.test(n)) n = `t${n}`;
  if (DART_RESERVED.has(n)) n = `${n}Token`;
  return n;
}

const dartDouble = (n: number) => (Number.isInteger(n) ? n.toFixed(1) : String(n));

function dartValue(v: TokenValue): string {
  switch (v.type) {
    case 'color':
      return `Color(0x${v.hex.slice(7, 9)}${v.hex.slice(1, 7)})`;
    case 'dimension':
      return dartDouble(v.unit === 'rem' ? v.value * 16 : v.value);
    case 'fontFamily':
      return `'${v.families[0]}'`;
    case 'fontWeight':
      return `FontWeight.w${Math.min(900, Math.max(100, Math.round(v.weight / 100) * 100))}`;
    case 'number':
      return dartDouble(v.value);
    case 'duration':
      return `Duration(milliseconds: ${Math.round(v.ms)})`;
  }
}

export const dartTokenEmitter: TokenEmitter = {
  lang: 'dart',
  ext: 'dart',
  emit(tokens, opts) {
    const className = opts?.className ?? 'DsTokens';
    if (!/^[A-Z][A-Za-z0-9_]*$/.test(className)) throw new Error(`invalid Dart class name ${JSON.stringify(className)}`);
    const names = nameAll(tokens, dartName);
    const lines = sorted(tokens).map((t) => {
      const value = t.aliasOf ? names.get(t.aliasOf)! : dartValue(t.value);
      return `  static const ${names.get(t.path)} = ${value};`;
    });
    return (
      `// ${GENERATED_HEADER}\n` +
      `import 'package:flutter/painting.dart';\n\n` +
      `abstract final class ${className} {\n${lines.join('\n')}\n}\n`
    );
  },
};

export const TOKEN_EMITTERS = new Map<string, TokenEmitter>([
  [cssTokenEmitter.lang, cssTokenEmitter],
  [dartTokenEmitter.lang, dartTokenEmitter],
]);
